def generate_ai_play_idea(api_key_str: str, model_str: str, mode_type: str, user_pref: str) -> dict:
    """Gemini API를 호출해 브리태니커 백과사전 스타일의 새로운 그림 주제/놀이 코스를 생성"""
    from google import genai
    from google.genai import types

    client = genai.Client(api_key=api_key_str)
    prompt = f"""
당신은 초등학생 딸아이와 아빠가 주말/일상에 함께 신나게 놀고 배울 수 있도록 아이디어를 주는 '브리태니커 어린이 백과사전 & 놀이 요정 AI'입니다.
요청 분야: {mode_type}
사용자 선택 조건: {user_pref}

아이의 지적 호기심(과학·자연·역사·예술 상식)과 상상력을 동시에 자극하도록 아래 JSON 형식으로만 응답하세요:
{{
  "domain": "선택된 테마 영역 이름",
  "headline": "한눈에 신나는 구체적인 그림 주제 또는 놀이 제목 (이모지 포함, 1줄)",
  "fact": "브리태니커 어린이 백과사전처럼 아이가 '우와, 진짜요?' 하고 감탄할 만한 재미있고 정확한 과학·자연·역사·문화 상식 (2문장)",
  "description": "어떻게 그리거나 놀면 재미있는지 아이 눈높이에서 다정하게 설명 (1~2문장)",
  "steps": [
    "1단계 스케치 또는 첫 번째 팁",
    "2단계 중심 표현 또는 두 번째 팁",
    "3단계 배경·채색 또는 세 번째 팁"
  ],
  "bonus_mission": "그림 속이나 놀이 중에 숨겨 넣을 수 있는 창의력 보너스 미션 1문장"
}}
"""
    response = client.models.generate_content(
        model=model_str,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            temperature=0.85,
        ),
    )
    return json.loads(response.text)


